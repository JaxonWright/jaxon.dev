#!/usr/bin/env node
// Generates src/app/services/rmrf-paths.ts: the fake `rm -rf /` output for the
// terminal easter egg. Mostly real Arch/Omarchy paths plus a run of this repo's
// actual files (from `git ls-files`, sampled node_modules and .git objects).
// Run: node scripts/gen-rmrf-paths.mjs
import { execSync } from 'node:child_process';
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const H = '/home/jaxon';
const REPO = `${H}/code/jaxon.dev`;
const KERNEL = '6.17.2-arch1-1';

/** Files of a directory followed by the directory itself, like `rm -rv` prints. */
const out = [];
const group = (dir, files) => { files.forEach(f => out.push(`removed '${dir}/${f}'`)); out.push(`removed directory '${dir}'`); };

group('/boot', ['vmlinuz-linux', 'initramfs-linux.img', 'initramfs-linux-fallback.img', 'intel-ucode.img']);
group('/etc/pacman.d', ['mirrorlist', 'gnupg/pubring.gpg']);
['pacman.conf', 'fstab', 'hostname', 'locale.conf', 'mkinitcpio.conf', 'os-release', 'passwd', 'shadow', 'sudoers'].forEach(f => out.push(`removed '/etc/${f}'`));

group(`${H}/.cache`, ['yay/omarchy-walker/PKGBUILD', 'chromium/Default/Cache/Cache_Data/data_1', 'fontconfig/CACHEDIR.TAG']);
group(`${H}/.config/hypr`, ['hyprland.conf', 'bindings.conf', 'monitors.conf', 'hypridle.conf', 'hyprlock.conf']);
group(`${H}/.config/waybar`, ['config.jsonc', 'style.css']);
group(`${H}/.config/nvim`, ['init.lua', 'lazy-lock.json', 'lua/plugins/theme.lua']);
group(`${H}/.local/share/omarchy`, ['bin/omarchy-theme-set', 'bin/omarchy-menu', 'themes/tokyo-night/colors.toml', 'themes/midnight/colors.toml', 'default/hypr/looknfeel.conf', 'version']);

// This repository, as it really is.
const files = execSync('git ls-files', { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean)
  .filter(f => !f.startsWith('src/assets/') && !f.startsWith('scripts/ascii-src/') && !f.startsWith('e2e/') && !f.endsWith('.spec.ts') && f !== 'src/app/services/.gitkeep' && f !== 'src/app/services/rmrf-paths.ts');
const nm = existsSync(join(root, 'node_modules/@angular/core/fesm2022'))
  ? readdirSync(join(root, 'node_modules/@angular/core/fesm2022')).filter(f => f.endsWith('.mjs')).slice(0, 4).map(f => `node_modules/@angular/core/fesm2022/${f}`)
  : ['node_modules/@angular/core/fesm2022/core.mjs'];
const objs = [];
for (const d of readdirSync(join(root, '.git/objects')).filter(d => /^[0-9a-f]{2}$/.test(d)).slice(0, 4)) {
  const o = readdirSync(join(root, '.git/objects', d))[0];
  if (o) objs.push(`.git/objects/${d}/${o}`);
}
[...nm, 'node_modules/rxjs/package.json', 'node_modules/.package-lock.json'].forEach(f => out.push(`removed '${REPO}/${f}'`));
out.push(`removed directory '${REPO}/node_modules'`);
[...objs, '.git/HEAD', '.git/index', '.git/config'].forEach(f => out.push(`removed '${REPO}/${f}'`));
out.push(`removed directory '${REPO}/.git'`);
files.forEach(f => out.push(`removed '${REPO}/${f}'`));
out.push(`removed directory '${REPO}/src'`, `removed directory '${REPO}'`);

group(`${H}/Desktop`, ['resume-aaaa-final-v2-THISONE.docx']);
group(`${H}/Documents/important-tax-stuff`, ['2025-return.pdf', 'W-2.pdf']);
['aaaaaa.txt', 'passwords.txt', 'snacks/wild-berry-skittles-ranking.md'].forEach(f => out.push(`removed '${H}/Documents/${f}'`));
group(`${H}/Downloads`, ['untitled(3).png', 'omarchy-3.1.iso', 'zoom_x86_64.pkg.tar.xz']);
group(`${H}/Pictures/Screenshots`, ['screenshot-2026-10-14_21-07-33.png', 'screenshot-2026-10-15_23-48-02.png']);
['.bashrc', '.bash_history', '.gitconfig', '.ssh/id_ed25519', '.ssh/known_hosts'].forEach(f => out.push(`removed '${H}/${f}'`));
out.push(`removed directory '${H}'`);

group(`/usr/lib/modules/${KERNEL}/kernel/drivers/gpu/drm/amd/amdgpu`, ['amdgpu.ko.zst']);
['modules.dep', 'modules.alias', 'vmlinuz'].forEach(f => out.push(`removed '/usr/lib/modules/${KERNEL}/${f}'`));
['libc.so.6', 'libstdc++.so.6', 'libsystemd.so.0', 'libwayland-client.so.0', 'libhyprlang.so.2'].forEach(f => out.push(`removed '/usr/lib/${f}'`));
group('/usr/bin', ['bash', 'ls', 'cat', 'pacman', 'yay', 'Hyprland', 'waybar', 'nvim', 'node', 'git', 'sudo', 'rm']);
group('/var/cache/pacman/pkg', ['linux-6.17.2.arch1-1-x86_64.pkg.tar.zst', 'hyprland-0.51.1-1-x86_64.pkg.tar.zst', 'nodejs-24.15.0-1-x86_64.pkg.tar.zst', 'glibc-2.42-2-x86_64.pkg.tar.zst']);
['/var/lib/pacman/local/ALPM_DB_VERSION', '/var/log/pacman.log'].forEach(p => out.push(`removed '${p}'`));

const ts = `// AUTO-GENERATED by scripts/gen-rmrf-paths.mjs. Do not edit by hand.\n/** Fake \`rm -rv /\` output for the terminal easter egg, in traversal order. */\nexport const RMRF_LINES: string[] = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(join(root, 'src/app/services/rmrf-paths.ts'), ts);
console.log(`${out.length} lines`);
